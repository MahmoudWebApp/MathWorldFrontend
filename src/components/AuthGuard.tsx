'use client';
import {useEffect} from 'react';
import {useSelector} from 'react-redux';
import {useLocale} from 'next-intl';
import {usePathname,useRouter} from '@/i18n/routing';
import type {RootState} from '@/store';
import {useGetStudentOnboardingQuery} from '@/store/api/usersApi';
import {MathWorldLoading} from '@/components/ui/MathWorldLoading';
export function AuthGuard({children}:{children:React.ReactNode}){
 const path=usePathname(),router=useRouter(),ar=useLocale()==='ar';
 const {user,isLoading,isAuthenticated,sessionUnavailable}=useSelector((s:RootState)=>s.auth);
 const admin=path==='/admin'||path.startsWith('/admin/');
 const supervisor=path==='/supervisor'||path.startsWith('/supervisor/');
 const student=path==='/dashboard'||path.startsWith('/dashboard/')||['/learning-stage','/profile','/social-accounts','/journey','/daily-challenge','/premium/report'].includes(path);
 const problemDetail=/^\/problems\/[^/]+$/.test(path);
 const account=path==='/notifications';
 const privateRoute=admin||supervisor||student||account||problemDetail;
 const role=user?.Role;
 const home=role==='Admin'?'/admin':role==='Supervisor'?'/supervisor':'/dashboard';
 const allowed=!!isAuthenticated&&!!user&&(admin?role==='Admin':supervisor?role==='Supervisor':student?role==='Student':problemDetail?role==='Student'||role==='Admin':account?role==='Admin'||role==='Student':true);
 const onboarding=useGetStudentOnboardingQuery(undefined,{skip:!isAuthenticated||role!=='Student'||!privateRoute,refetchOnMountOrArgChange:true,pollingInterval:15000,skipPollingIfUnfocused:true});
 const requiresSetup=allowed&&role==='Student'&&privateRoute&&path!=='/learning-stage'&&onboarding.data?.NextStep!=='Complete';
 const target=privateRoute&&!allowed?(!isAuthenticated?'/login':home):requiresSetup&&onboarding.data?'/learning-stage':null;
 useEffect(()=>{if(!isLoading&&!sessionUnavailable&&target)router.replace(target);},[isLoading,sessionUnavailable,target,router]);
 if(!privateRoute)return <>{children}</>;
 if(sessionUnavailable)return <div className="mx-auto max-w-lg p-8 text-center"><p role="alert">{ar?'تعذّر التحقق من الجلسة.':'Unable to verify session.'}</p><button className="sr-wave-button mt-4 rounded-xl px-4 py-2 text-white" onClick={()=>window.dispatchEvent(new Event('mathworld:retry-auth'))}>{ar?'إعادة المحاولة':'Retry'}</button></div>;
 if(requiresSetup&&onboarding.isError&&!onboarding.data)return <div className="mx-auto max-w-lg p-8 text-center"><p role="alert">{ar?'تعذّر التحقق من إعداد الحساب.':'Could not check account setup.'}</p><button className="sr-wave-button mt-4 rounded-xl px-4 py-2 text-white" onClick={()=>void onboarding.refetch()}>{ar?'إعادة المحاولة':'Retry'}</button></div>;
 if(isLoading||!allowed||requiresSetup)return <div className="p-8"><MathWorldLoading compact/></div>;
 return <>{children}</>;
}
